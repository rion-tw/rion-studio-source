import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const escape = (value) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
const languages = ["en", "zh-TW", "zh-CN", "ja"];

export function buildWorkspaceStartPage(root = new URL("../", import.meta.url)) {
  const read = (path) => readFileSync(new URL(path, root), "utf8");
  const catalog = JSON.parse(read("src/shared/workspaceWebCatalog.json"));
  const categories = JSON.parse(read("src/shared/workspaceWebCategories.json"));
  const translations = Object.fromEntries(languages.map((language) => [language,
    JSON.parse(read(`src/renderer/src/i18n/${language}.json`))]));
  const translated = (key) => languages.map((language) =>
    `<span data-language="${language}">${escape(translations[language][key])}</span>`).join("");
  const cards = (sites) => sites.map((site) => {
    const mime = { svg: "image/svg+xml", png: "image/png", jpg: "image/jpeg", ico: "image/x-icon", webp: "image/webp" }[site.brandAsset.split(".").at(-1)];
    if (!mime) throw new Error(`Unsupported website brand asset: ${site.brandAsset}`);
    const image = readFileSync(new URL(`src/renderer/src/assets/workspace-web/${site.brandAsset}`, root)).toString("base64");
    const domain = new URL(site.startUrl).hostname.replace(/^www\./u, "");
    return `<a class="site" data-workspace-start-site="${site.id}" href="${escape(site.startUrl)}" target="_self"><img class="brand${site.brandImagePresentation === "cover" ? " cover" : ""}" alt="" width="40" height="40" src="data:${mime};base64,${image}"><span><span class="name">${site.nameKey ? translated(site.nameKey) : escape(site.name)}</span><span class="domain">${escape(domain)}</span></span></a>`;
  }).join("\n");
  const groups = Object.entries(categories).map(([id, key]) =>
    `<section class="site-group" data-workspace-start-category="${id}" aria-labelledby="category-${id}"><h2 id="category-${id}">${translated(key)}</h2><div class="sites">${cards(catalog.filter((site) => site.category === id))}</div></section>`).join("\n");
  return `<!doctype html>\n<!-- Generated by scripts/generateWorkspaceStartPage.mjs. Do not edit. -->
<html lang="en" data-theme="light"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'">
<title>Rion Studio</title><style>${read("src/shared/designTokens.css")}\n${read("src/renderer/runtime-workspace-start.css")}</style></head>
<body data-rion-workspace-start><main><header><span class="eyebrow">RION STUDIO</span><h1 id="website-title">${translated("workspaces.webStartTitle")}</h1><p class="hint">${translated("workspaces.webStartHint")}</p></header><nav class="site-groups" aria-labelledby="website-title">${groups}</nav></main></body></html>\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("src/shared/generated/workspace-start.html", root), buildWorkspaceStartPage());
}
