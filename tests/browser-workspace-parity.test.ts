    for (const caseId of caseIds) {
      v1Case(caseId, () => {
        const entry = entries.get(caseId);
        expect(entry).toBeDefined();
        expect(entry?.classification).not.toBe("unresolved");
        expect(entry?.behaviorEvidence.file).toMatch(/^(tests\/|crates\/|src-tauri\/src\/system_runtime\.rs)/);
        expect(entry?.behaviorEvidence.test.length).toBeGreaterThan(0);
      });
    }
